# ------------------------------------------------------------------ LZW encoder ---------------


@dataclass
class LzwOpts:
    initial_clear: bool = True
    clear_every: Optional[int] = None  # write a clear code after every N data codes
    eoi: bool = True
    tail: bytes = b""  # raw bytes appended after the end-of-information code (data past EOI)
    subblock: object = 255  # int: fixed sub-block size; "rand": random 1..255


class LzwStats:
    def __init__(self):
        self.max_width = 0
        self.codes = 0
        self.codes_after_full = 0
        self.clears = 0


def lzw_codes(indices, m, o: LzwOpts, stats: LzwStats):
    """Returns the (code, width) list for `indices`."""
    clear = 1 << m
    eoi = clear + 1
    out = []
    table = {}
    nxt = clear + 2
    w = m + 1

    def put(code):
        nonlocal w
        out.append((code, w))
        stats.max_width = max(stats.max_width, w)

    def add_step(real_key):
        """The per-code table update; real_key None for the final code (virtual entry)."""
        nonlocal nxt, w
        if nxt < 4096:
            if real_key is not None:
                table[real_key] = nxt
            e = nxt
            nxt += 1
            if e == (1 << w) and w < 12:
                w += 1
        else:
            stats.codes_after_full += 1

    def do_clear():
        nonlocal nxt, w, table
        put(clear)
        table = {}
        nxt = clear + 2
        w = m + 1
        stats.clears += 1

    if o.initial_clear:
        do_clear()
    cur = None
    since_clear = 0
    for v in indices:
        assert 0 <= v < clear
        if cur is None:
            cur = v
            continue
        key = (cur, v)
        if key in table:
            cur = table[key]
            continue
        put(cur)
        stats.codes += 1
        add_step(key)
        since_clear += 1
        cur = v
        if o.clear_every and since_clear == o.clear_every:
            do_clear()
            cur = v  # the string restarts at v: it was not yet emitted
            since_clear = 0
    if cur is not None:
        put(cur)
        stats.codes += 1
        add_step(None)
    if o.eoi:
        put(eoi)
    return out


def pack_codes(codes):
    out = bytearray()
    acc = 0
    nb = 0
    for c, w in codes:
        assert 0 <= c < (1 << w)
        acc |= c << nb
        nb += w
        while nb >= 8:
            out.append(acc & 255)
            acc >>= 8
            nb -= 8
    if nb:
        out.append(acc & 255)
    return bytes(out)


def sub_blocks(data, mode, rng):
    """Splits `data` into a terminated sub-block chain."""
    out = bytearray()
    i = 0
    while i < len(data):
        if mode == "rand":
            n = rng.randint(1, 255)
        else:
            n = int(mode)
        n = min(n, len(data) - i, 255)
        out.append(n)
        out += data[i:i + n]
        i += n
    out.append(0)
    return bytes(out)


def lzw_decode_check(codes_bytes_chain_free, m, want):
    """Self-check only (never an expectation): an ordinary LZW decoder over the packed bits must
    give back exactly `want`; catches generator bugs and pins the width rule to the standard one."""
    clear = 1 << m
    eoi = clear + 1
    bits = int.from_bytes(codes_bytes_chain_free, "little")
    nbits = len(codes_bytes_chain_free) * 8
    pos = 0
    width = m + 1
    nxt = clear + 2
    table = {}
    prev = None
    res = []

    def s(c):
        return [c] if c < clear else table[c]

    while pos + width <= nbits and len(res) < len(want):
        code = (bits >> pos) & ((1 << width) - 1)
        pos += width
        if code == clear:
            width = m + 1
            nxt = clear + 2
            table = {}
            prev = None
            continue
        if code == eoi:
            break
        if prev is None:
            assert code < clear
            res += s(code)
            prev = code
            continue
        if code < nxt:
            cs = s(code)
        else:
            assert code == nxt
            cs = s(prev) + [s(prev)[0]]
        res += cs
        if nxt < 4096:
            table[nxt] = s(prev) + [cs[0]]
            nxt += 1
            if nxt >= (1 << width) and width < 12:
                width += 1
        prev = code
    assert res[:len(want)] == want, "LZW self-check failed"


# ------------------------------------------------------------------ GIF writer ----------------

Color = Tuple[int, int, int]


@dataclass
class Frame:
    x: int
    y: int
    w: int
    h: int
    image: List[int]  # w*h indices, row-major in the LOGICAL (de-interlaced) picture
    m: int = 8
    interlace: bool = False
    lct: Optional[List[Color]] = None
    gce: Optional[Tuple[int, Optional[int], int]] = None  # (disposal, transparent index, delay)
    gce_extra: bytes = b""  # extra bytes inside the GCE sub-block (ignored by decoders)
    pre: List[bytes] = field(default_factory=list)  # raw blocks before the GCE
    lzw: LzwOpts = field(default_factory=LzwOpts)
    limit: Optional[int] = None  # code only the first `limit` file-order pixels (too few)
    extra: List[int] = field(default_factory=list)  # extra indices coded past w*h


def file_order(w, h, interlace):
    """File order of a w x h frame's pixels as (x, y); the interlace passes are the GIF89a ones."""
    if not interlace:
        rows = list(range(h))
    else:
        rows = []
        for start, step in ((0, 8), (4, 8), (2, 4), (1, 2)):
            rows += list(range(start, h, step))
    assert sorted(rows) == list(range(h))
    return [(x, y) for y in rows for x in range(w)]


def coded_stream(fr: Frame):
    pos = file_order(fr.w, fr.h, fr.interlace)
    vals = [fr.image[y * fr.w + x] for x, y in pos]
    if fr.limit is not None:
        vals = vals[:fr.limit]
    return vals + list(fr.extra)


def pal_bytes(pal):
    n = len(pal)
    assert n in (2, 4, 8, 16, 32, 64, 128, 256), n
    return b"".join(bytes(c) for c in pal)


def size_bits(n):
    return n.bit_length() - 2  # n = 2^(bits+1)


def ext(label, subs):
    out = bytes([0x21, label])
    for s in subs:
        assert 0 < len(s) < 256
        out += bytes([len(s)]) + s
    return out + b"\x00"


def netscape(loop, ident=b"NETSCAPE2.0", first=1):
    return ext(0xFF, [ident, bytes([first]) + struct.pack("<H", loop)])


def write_frame(fr: Frame, rng, stats_out):
    out = bytearray()
    for b in fr.pre:
        out += b
    if fr.gce is not None:
        disposal, transp, delay = fr.gce
        packed = (disposal << 2) | (1 if transp is not None else 0)
        body = bytes([packed]) + struct.pack("<H", delay) + bytes([transp or 0]) + fr.gce_extra
        out += ext(0xF9, [body])
    packed = (0x80 | size_bits(len(fr.lct))) if fr.lct else 0
    if fr.interlace:
        packed |= 0x40
    out += b"\x2C" + struct.pack("<HHHHB", fr.x, fr.y, fr.w, fr.h, packed)
    if fr.lct:
        out += pal_bytes(fr.lct)
    out.append(fr.m)
    stats = LzwStats()
    vals = coded_stream(fr)
    codes = lzw_codes(vals, fr.m, fr.lzw, stats)
    packed_bits = pack_codes(codes)
    # the roundtrip self-check covers streams that carry all their codes
    if fr.lzw.initial_clear or vals:
        lzw_decode_check(packed_bits, fr.m, vals)
    out += sub_blocks(packed_bits + fr.lzw.tail, fr.lzw.subblock, rng)
    stats_out.append(stats)
    return bytes(out)


@dataclass
class Gif:
    W: int
    H: int
    frames: List[Frame]
    gct: Optional[List[Color]] = None
    loop: Optional[int] = None  # NETSCAPE loop extension right after the global table
    loop_ident: bytes = b"NETSCAPE2.0"
    loop_first: int = 1
    version: bytes = b"GIF89a"
    bg_index: int = 0
    header_ext: List[bytes] = field(default_factory=list)  # extra extensions before frame 0
    expect_loop: Optional[int] = None  # override for the expected loop count


def write_gif(g: Gif, rng, stats_out):
    out = bytearray(g.version)
    packed = 0x70  # color resolution 8 bits
    if g.gct:
        packed |= 0x80 | size_bits(len(g.gct))
    out += struct.pack("<HHBBB", g.W, g.H, packed, g.bg_index, 0)
    if g.gct:
        out += pal_bytes(g.gct)
    if g.loop is not None:
        out += netscape(g.loop, g.loop_ident, g.loop_first)
    for b in g.header_ext:
        out += b
    for fr in g.frames:
        out += write_frame(fr, rng, stats_out)
    out.append(0x3B)
    return bytes(out)


# ------------------------------------------------------------------ compositor ----------------


def clip_rect(fr: Frame, W, H):
    x0, y0 = min(fr.x, W), min(fr.y, H)
    x1, y1 = min(fr.x + fr.w, W), min(fr.y + fr.h, H)
    if x1 <= x0 or y1 <= y0:
        return (0, 0, 0, 0)
    return (x0, y0, x1, y1)


def compose(g: Gif):
    """Expected (delayMs, disposal, rect, canvas) per frame, from the source indices."""
    W, H = g.W, g.H
    canvas = [0] * (W * H)
    saved = {}
    prev = None
    res = []
    for fr in g.frames:
        if prev is not None:
            pdisp, prect = prev
            x0, y0, x1, y1 = prect
            for y in range(y0, y1):
                for x in range(x0, x1):
                    if pdisp == 2:
                        canvas[y * W + x] = 0
                    elif pdisp == 3:
                        canvas[y * W + x] = saved[(x, y)]
        disp = fr.gce[0] if fr.gce else 0
        transp = fr.gce[1] if fr.gce else None
        delay = fr.gce[2] if fr.gce else 0
        rect = clip_rect(fr, W, H)
        if disp == 3:
            saved = {}
            x0, y0, x1, y1 = rect
            for y in range(y0, y1):
                for x in range(x0, x1):
                    saved[(x, y)] = canvas[y * W + x]
        pal = fr.lct if fr.lct else (g.gct if g.gct else [])
        vals = coded_stream(fr)
        pos = file_order(fr.w, fr.h, fr.interlace)
        for i in range(min(len(vals), fr.w * fr.h)):
            x, y = pos[i]
            idx = vals[i]
            cx, cy = fr.x + x, fr.y + y
            if cx >= W or cy >= H:
                continue
            if transp is not None and idx == transp:
                continue
            if idx < len(pal):
                r, gg, b = pal[idx]
                canvas[cy * W + cx] = 0xFF000000 | (r << 16) | (gg << 8) | b
            else:
                canvas[cy * W + cx] = 0xFF000000
        res.append((delay * 10, disp, rect, list(canvas)))
        prev = (disp, rect)
    return res


def loop_of(g: Gif):
    if g.expect_loop is not None:
        return g.expect_loop
    return g.loop if (g.loop is not None and g.loop_first == 1 and
                      g.loop_ident in (b"NETSCAPE2.0", b"ANIMEXTS1.0")) else -1


