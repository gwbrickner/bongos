#!/usr/bin/env python3
"""Generates tests/data/gfx/gif-fixtures.z for libs/gfx's GIF decoder tests (M12.7, D-163/D-164).

An independent GIF writer (Python stdlib only; ARCHITECTURE section 0's host-tool exception) with
its own LZW ENCODER and its own animation COMPOSITOR. Each fixture is built from the pixel indices
the generator starts with; the expected canvases are computed from those indices and the semantics
below, never by parsing the bytes that were written. libs/gfx/gif.c must reproduce every canvas
exactly (tolerance 0).

Semantics implemented here (GIF89a plus the choices documented in gfx-image.h / D-164):
  * canvas W x H starts fully transparent (0); the logical screen's background color is ignored
  * a frame's pixels are drawn in file order (interlaced files: rows 0,8,..; 4,12,..; 2,6,..;
    1,3,..); the transparent index leaves the canvas alone; an index beyond the frame's palette
    (its local table if it has one, else the global one, else no palette) draws opaque black
  * frames are clipped to the canvas; the reported rectangle is the clipped one ({0,0,0,0} if empty)
  * before frame k is drawn, frame k-1's disposal is applied to its clipped rectangle: 2 clears it
    to transparent, 3 restores what was there before frame k-1 was drawn (frame 0 restores to
    transparent), everything else (0, 1, 4..7) leaves the canvas alone
  * a stream that ends early (too few codes, or no end-of-information code) leaves the rest of the
    frame untouched; codes past the frame's pixel count are ignored
  * the first loop extension (NETSCAPE2.0 / ANIMEXTS1.0 with sub-block byte 1 == 1) sets the loop
    count; without one the loop count is -1

The LZW encoder is written from the GIF89a appendix independently of the C decoder: after each
code it adds a table entry and widens the code when the entry just added equals 2^width, which is
one step ahead of the decoder (the final code counts as adding an entry too, so the end-of-
information code is written at the width the decoder will read it with). Once the table holds 4096
entries it stops adding and keeps emitting at width 12 (a deferred clear).

Container (zlib-compressed as a whole, prefixed by u32 LE raw length), a sequence of records:
  u16 nameLen, name, u32 W, u32 H, u32 frameCount, i32 loopCount, u32 dataLen, data,
  then per frame: u32 delayMs, u8 disposal, i32 x0, y0, x1, y1 (the clipped rectangle),
  then W*H little-endian u32 (premultiplied 0xAARRGGBB canvas after that frame is drawn).
Every fixture decodes with STATUS_OK; malformed inputs are crafted in tests/host/gfx_gif_test.c.

Run manually (`python3 tests/data/gfx/gen_gif.py`) when adding fixtures; the output is checked in,
not regenerated by the build.
"""
