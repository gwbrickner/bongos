def seeded(name):
    return random.Random(zlib.crc32(name.encode()))


def palette(n, rng):
    pal = []
    for i in range(n):
        pal.append((rng.randrange(256), rng.randrange(256), rng.randrange(256)))
    return pal


def rand_image(w, h, ncolors, rng):
    return [rng.randrange(ncolors) for _ in range(w * h)]


def full(W, H, ncolors, rng, **kw):
    return Frame(0, 0, W, H, rand_image(W, H, ncolors, rng), **kw)


