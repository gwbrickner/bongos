def main():
    blob = bytearray()
    fx = fixtures()
    names = set()
    agg = LzwStats()
    for name, g in fx:
        assert name not in names, name
        names.add(name)
        rng = seeded(name + "/layout")
        stats = []
        data = write_gif(g, rng, stats)
        for s in stats:
            agg.max_width = max(agg.max_width, s.max_width)
            agg.codes_after_full += s.codes_after_full
        frames = compose(g)
        nb = name.encode()
        blob += struct.pack("<H", len(nb)) + nb
        blob += struct.pack("<IIIiI", g.W, g.H, len(frames), loop_of(g), len(data)) + data
        for delay_ms, disp, rect, canvas in frames:
            assert len(canvas) == g.W * g.H
            blob += struct.pack("<IB4i", delay_ms, disp, *rect)
            blob += b"".join(struct.pack("<I", v) for v in canvas)
    # generator assertions: the corner cases the decoder tests rely on are really present
    assert agg.max_width == 12, "no stream reached 12-bit codes"
    assert agg.codes_after_full > 100, "no stream continued past a full table"
    with open(os.path.join(HERE, "gif-fixtures.z"), "wb") as f:
        f.write(struct.pack("<I", len(blob)) + zlib.compress(bytes(blob), 9))
    print(len(fx), "fixtures,", len(blob), "bytes raw")


if __name__ == "__main__":
    main()
