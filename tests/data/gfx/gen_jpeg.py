#!/usr/bin/env python3
"""Generates tests/data/gfx/jpeg-fixtures.z for libs/gfx's JPEG decoder tests (M12.7, D-160..D-165).

An independent JPEG *encoder* written from ITU-T T.81 (Python stdlib only; ARCHITECTURE §0's
host-tool exception) writes many files across frame types, sampling layouts, scan scripts, Huffman
tables, restart intervals and marker variants. The expected pixels are NOT obtained by parsing the
bitstream: they are computed from the quantized coefficient arrays the encoder itself started
from, through an exact integer model of the decoder pipeline (D-161): dequantize, clamp to int16,
the LLM "islow" integer IDCT, replicated chroma upsampling (sx = x*Hc//Hmax), libjpeg's 16-bit
fixed-point YCbCr conversion. So Huffman decoding, MCU layout, progression and restart handling in
the C decoder are checked against something other than the C decoder.

Container: u32 LE rawLen, then zlib(raw). raw is a sequence of records:
  u16 nameLen, name, i32 status (0, or the expected Status of the decode), u8 flags (bit0: the
  expected field is a CRC-32 of the pixel bytes instead of the pixels), u32 width, u32 height,
  u32 dataLen, data, then (only when status == 0) width*height LE u32 opaque ARGB pixels, or the
  4-byte CRC-32 (zlib.crc32 of those pixel bytes) when flags bit0 is set.
Names are  jg_<group>__<variant>  : every variant of a group encodes the very same coefficients, so
the C decoder must give identical pixels for all of them (the test checks that too).

Run manually (`python3 tests/data/gfx/gen_jpeg.py`); the output is checked in, not regenerated by
the build.
"""
