def descale(x, n):
    return (x + (1 << (n - 1))) >> n  # Python's >> is arithmetic on negatives


def idct_1d(v):
    z1 = (v[2] + v[6]) * 4433
    t2 = z1 - v[6] * 15137
    t3 = z1 + v[2] * 6270
    t0 = (v[0] + v[4]) * 8192
    t1 = (v[0] - v[4]) * 8192
    t10, t13, t11, t12 = t0 + t3, t0 - t3, t1 + t2, t1 - t2
    o0, o1, o2, o3 = v[7], v[5], v[3], v[1]
    z1, z2, z3, z4 = o0 + o3, o1 + o2, o0 + o2, o1 + o3
    z5 = (z3 + z4) * 9633
    o0 *= 2446
    o1 *= 16819
    o2 *= 25172
    o3 *= 12299
    z1 *= -7373
    z2 *= -20995
    z3 *= -16069
    z4 *= -3196
    z3 += z5
    z4 += z5
    o0 += z1 + z3
    o1 += z2 + z4
    o2 += z2 + z3
    o3 += z1 + z4
    return [t10 + o3, t11 + o2, t12 + o1, t13 + o0, t13 - o0, t12 - o1, t11 - o2, t10 - o3]


def clamp(x, lo, hi):
    return lo if x < lo else hi if x > hi else x


def idct_block(coef, q):
    """coef, q: natural order. Returns 64 clamped 0..255 samples (row-major)."""
    d = [clamp(coef[i] * q[i], -32768, 32767) for i in range(64)]
    ws = [0] * 64
    for c in range(8):
        out = idct_1d([d[8 * i + c] for i in range(8)])
        for i in range(8):
            ws[8 * i + c] = descale(out[i], 11)
    res = [0] * 64
    for r in range(8):
        out = idct_1d(ws[8 * r:8 * r + 8])
        for i in range(8):
            res[8 * r + i] = clamp(descale(out[i], 18) + 128, 0, 255)
    return res


def ycc_to_rgb(y, cb, cr):
    cb -= 128
    cr -= 128
    r = y + ((91881 * cr + 32768) >> 16)
    g = y + ((-22554 * cb - 46802 * cr + 32768) >> 16)
    b = y + ((116130 * cb + 32768) >> 16)
    return clamp(r, 0, 255), clamp(g, 0, 255), clamp(b, 0, 255)


def ceil_div(a, b):
    return (a + b - 1) // b


class Frame:
    """A frame's parameters plus quantized coefficients: coefs[c][by][bx] -> 64 ints, natural
    order, on the padded block grid (bw = mcusX*Hc by bh = mcusY*Vc)."""

    def __init__(self, w, h, comps, qtables, colorspace):
        self.w, self.h = w, h
        self.comps = comps  # list of dicts: id, h, v, tq
        self.qtables = qtables  # id -> 64 ints (natural order) as latched by the FIRST scan
        self.colorspace = colorspace  # 'gray' | 'ycc' | 'rgb'
        self.hmax = max(c["h"] for c in comps)
        self.vmax = max(c["v"] for c in comps)
        self.mcusx = ceil_div(w, 8 * self.hmax)
        self.mcusy = ceil_div(h, 8 * self.vmax)
        for c in comps:
            c["compw"] = ceil_div(w * c["h"], self.hmax)
            c["comph"] = ceil_div(h * c["v"], self.vmax)
            c["nbx"] = ceil_div(c["compw"], 8)
            c["nby"] = ceil_div(c["comph"], 8)
            c["bw"] = self.mcusx * c["h"]
            c["bh"] = self.mcusy * c["v"]
        self.coefs = None
        self.latched_q = None  # per-component q actually used for the model (set by the encoder)

    def expected(self, qs=None):
        """Model output: list of h rows of w opaque ARGB pixels. qs: per-component natural q."""
        qs = qs or [self.qtables[c["tq"]] for c in self.comps]
        cache = {}
        planes = []
        for ci, c in enumerate(self.comps):
            pw = c["nbx"] * 8
            ph = c["nby"] * 8
            plane = [[0] * pw for _ in range(ph)]
            for by in range(c["nby"]):
                for bx in range(c["nbx"]):
                    blk = self.coefs[ci][by][bx]
                    key = (tuple(blk), tuple(qs[ci]))
                    px = cache.get(key)
                    if px is None:
                        px = cache[key] = idct_block(blk, qs[ci])
                    for r in range(8):
                        plane[by * 8 + r][bx * 8:bx * 8 + 8] = px[8 * r:8 * r + 8]
            planes.append(plane)
        rows = []
        for y in range(self.h):
            row = []
            for x in range(self.w):
                s = []
                for ci, c in enumerate(self.comps):
                    s.append(planes[ci][y * c["v"] // self.vmax][x * c["h"] // self.hmax])
                if self.colorspace == "gray":
                    r = g = b = s[0]
                elif self.colorspace == "rgb":
                    r, g, b = s
                else:
                    r, g, b = ycc_to_rgb(*s)
                row.append(0xFF000000 | (r << 16) | (g << 8) | b)
            rows.append(row)
        return rows


# ------------------------------------------------------------------ forward DCT + images -------

COS = [[math.cos((2 * x + 1) * u * math.pi / 16) for x in range(8)] for u in range(8)]


def fdct_block(px):
    """px: 64 samples (already level-shifted by -128). Returns 64 float coefficients (natural)."""
    tmp = [0.0] * 64
    for y in range(8):
        for u in range(8):
            tmp[8 * y + u] = sum(px[8 * y + x] * COS[u][x] for x in range(8))
    out = [0.0] * 64
    for u in range(8):
        for v in range(8):
            s = sum(tmp[8 * y + u] * COS[v][y] for y in range(8))
            cu = math.sqrt(0.5) if u == 0 else 1.0
            cv = math.sqrt(0.5) if v == 0 else 1.0
            out[8 * v + u] = 0.25 * cu * cv * s
    return out


def natural_rgb(w, h, seed=1):
    """A smooth-plus-edges test picture: gradients, a disc, diagonal stripes, some noise."""
    rng = Rng(seed)
    img = []
    for y in range(h):
        row = []
        for x in range(w):
            fx, fy = x / max(w - 1, 1), y / max(h - 1, 1)
            r = 40 + 180 * fx
            g = 30 + 190 * fy
            b = 200 - 120 * (fx + fy) / 2
            dx, dy = x - w * 0.6, y - h * 0.4
            if dx * dx + dy * dy < (min(w, h) * 0.3) ** 2:
                r, g, b = 230, 60 + 100 * fx, 40
            if (x + y) % 16 < 3:
                r, g, b = 255 - r, 255 - g, 255 - b
            n = rng.below(9) - 4
            row.append(tuple(clamp(int(round(v)) + n, 0, 255) for v in (r, g, b)))
        img.append(row)
    return img


def rgb_to_ycc(r, g, b):
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = -0.168736 * r - 0.331264 * g + 0.5 * b + 128
    cr = 0.5 * r - 0.418688 * g - 0.081312 * b + 128
    return y, cb, cr


def make_natural(w, h, layout, colorspace, q, seed=1, tqs=None):
    """layout: list of (h, v). Returns a Frame with FDCT'd, quantized coefficients. q: natural q
    per component (list of 64-lists) or a single one applied to all."""
    ncomp = len(layout)
    tqs = tqs or [0] + [1] * (ncomp - 1)
    ids = {"gray": [1], "ycc": [1, 2, 3], "rgb": [1, 2, 3]}[colorspace]
    comps = [{"id": ids[i], "h": layout[i][0], "v": layout[i][1], "tq": tqs[i]} for i in range(ncomp)]
    qtables = {}
    for i, c in enumerate(comps):
        qtables[c["tq"]] = q[i] if isinstance(q[0], list) else q
    f = Frame(w, h, comps, qtables, colorspace)
    img = natural_rgb(w, h, seed)
    src = []  # per-component full-resolution float planes
    for ci in range(ncomp):
        src.append([[0.0] * w for _ in range(h)])
    for y in range(h):
        for x in range(w):
            r, g, b = img[y][x]
            if colorspace == "gray":
                vals = (0.299 * r + 0.587 * g + 0.114 * b,)
            elif colorspace == "rgb":
                vals = (r, g, b)
            else:
                vals = rgb_to_ycc(r, g, b)
            for ci in range(ncomp):
                src[ci][y][x] = vals[ci]
    f.coefs = []
    for ci, c in enumerate(comps):
        # component plane: box-average the source pixels that map onto each sample
        pw, ph = c["bw"] * 8, c["bh"] * 8
        plane = [[0.0] * pw for _ in range(ph)]
        ys_of = [[y for y in range(h) if y * c["v"] // f.vmax == cy] for cy in range(c["comph"])]
        xs_of = [[x for x in range(w) if x * c["h"] // f.hmax == cx] for cx in range(c["compw"])]
        for cy in range(c["comph"]):
            for cx in range(c["compw"]):
                pts = [src[ci][y][x] for y in ys_of[cy] for x in xs_of[cx]]
                # fractional ratios leave samples nothing maps to (D-161); any value will do
                plane[cy][cx] = sum(pts) / len(pts) if pts else plane[cy][max(cx - 1, 0)]
        for cy in range(ph):  # edge replication into the padded area
            for cx in range(pw):
                plane[cy][cx] = plane[min(cy, c["comph"] - 1)][min(cx, c["compw"] - 1)]
        qq = qtables[c["tq"]]
        blocks = []
        for by in range(c["bh"]):
            row = []
            for bx in range(c["bw"]):
                px = [plane[by * 8 + r][bx * 8 + x] - 128 for r in range(8) for x in range(8)]
                co = fdct_block(px)
                blk = [int(round(co[i] / qq[i])) for i in range(64)]
                assert all(abs(blk[i] * qq[i]) < 32000 for i in range(64))
                assert abs(blk[0]) <= 1023 and all(abs(blk[i]) <= 1023 for i in range(1, 64))
                row.append(blk)
            blocks.append(row)
        f.coefs.append(blocks)
    return f


def make_random(w, h, layout, colorspace, q, seed, tqs=None):
    """Random quantized coefficients hitting every DC category 0..11 (as differences), AC sizes
    1..10, long zero runs (ZRL) and k = 63, on every block of the padded grid."""
    rng = Rng(seed)
    ncomp = len(layout)
    tqs = tqs or [0] + [1] * (ncomp - 1)
    ids = {"gray": [1], "ycc": [1, 2, 3], "rgb": [1, 2, 3]}[colorspace]
    comps = [{"id": ids[i], "h": layout[i][0], "v": layout[i][1], "tq": tqs[i]} for i in range(ncomp)]
    qtables = {}
    for i, c in enumerate(comps):
        qtables[c["tq"]] = q[i] if isinstance(q[0], list) else q
    f = Frame(w, h, comps, qtables, colorspace)
    f.coefs = []
    for ci, c in enumerate(comps):
        blocks = []
        for by in range(c["bh"]):
            row = []
            for bx in range(c["bw"]):
                blk = [0] * 64
                cat = rng.below(12)
                if cat == 11:
                    blk[0] = 1023 if (bx + by) % 2 == 0 else -1023
                elif cat == 0:
                    blk[0] = 0
                else:
                    mag = rng.range(1 << (cat - 1), min((1 << cat) - 1, 1023))
                    blk[0] = mag if rng.below(2) else -mag
                mode = rng.below(4)
                if mode == 1:  # sparse with long runs
                    for _ in range(rng.range(1, 4)):
                        k = rng.range(1, 63)
                        blk[ZZ[k]] = rng.range(1, 3) * (1 if rng.below(2) else -1)
                elif mode == 2:  # dense low frequencies, mixed sizes
                    for k in range(1, rng.range(2, 30)):
                        s = rng.range(0, 10)
                        if s:
                            mag = rng.range(1 << (s - 1), (1 << s) - 1)
                            blk[ZZ[k]] = mag if rng.below(2) else -mag
                elif mode == 3:  # last coefficient set
                    blk[ZZ[63]] = rng.range(1, 1023) * (1 if rng.below(2) else -1)
                    blk[ZZ[rng.range(1, 62)]] = rng.range(1, 60)
                row.append(blk)
            blocks.append(row)
        f.coefs.append(blocks)
    qq = qtables
    assert all(abs(cf * qq[c["tq"]][i]) < 32768 for ci, c in enumerate(comps)
               for r in f.coefs[ci] for blk in r for i, cf in enumerate(blk))
    return f


def flat_q(v):
    return [v] * 64


def std_q(scale=1):
    """A JPEG-ish quantization table (natural order), coarser at high frequencies."""
    return [max(1, (4 + (i // 8) + (i % 8)) * scale // 2) for i in range(64)]


# ------------------------------------------------------------------ Huffman tables -------------


def optimal_table(freq_in, pad=0):
    """T.81 Annex K.2/K.3 (Figures K.1, K.2): code lengths limited to 16, the reserved all-ones
    code kept free by a pseudo-symbol 256. Returns (bits[1..16], huffval)."""
    freq = list(freq_in) + [0] * (257 - len(freq_in))
    freq[256] = 1
    codesize = [0] * 257
    others = [-1] * 257
    while True:
        c1, v = -1, 1 << 60
        for i in range(257):
            if freq[i] and freq[i] <= v:
                v, c1 = freq[i], i
        c2, v = -1, 1 << 60
        for i in range(257):
            if freq[i] and freq[i] <= v and i != c1:
                v, c2 = freq[i], i
        if c2 < 0:
            break
        freq[c1] += freq[c2]
        freq[c2] = 0
        codesize[c1] += 1
        while others[c1] >= 0:
            c1 = others[c1]
            codesize[c1] += 1
        others[c1] = c2
        codesize[c2] += 1
        while others[c2] >= 0:
            c2 = others[c2]
            codesize[c2] += 1
    bits = [0] * 64
    for i in range(257):
        if codesize[i]:
            bits[codesize[i]] += 1
    for i in range(63, 16, -1):
        while bits[i] > 0:
            j = i - 2
            while bits[j] == 0:
                j -= 1
            bits[i] -= 2
            bits[i - 1] += 1
            bits[j + 1] += 2
            bits[j] -= 1
    i = 16
    while bits[i] == 0:
        i -= 1
    bits[i] -= 1
    vals = []
    for length in range(1, 33):
        for s in range(256):
            if codesize[s] == length:
                vals.append(s)
    return bits[1:17], vals


def skewed_table(used):
    """A table with a 16-bit code: exponentially skewed frequencies over `used` plus padding
    symbols (unused ones are legal in a DHT) until there are at least 20."""
    syms = sorted(set(used))
    extra = [s for s in range(0x11, 0x100) if s not in syms]
    while len(syms) < 20:
        syms.append(extra.pop(0))
    freq = [0] * 256
    for rank, s in enumerate(sorted(syms)):
        freq[s] = 1 << min(rank, 22)  # bounded so the unlimited tree stays <= 32 deep
    bits, vals = optimal_table(freq)
    assert max(i + 1 for i, n in enumerate(bits) if n) == 16, bits
    return bits, vals


def flat_table(used):
    syms = sorted(set(used))
    length = 1
    while (1 << length) < len(syms) + 1:
        length += 1
    bits = [0] * 16
    bits[length - 1] = len(syms)
    return bits, syms


def canonical_codes(bits, vals):
    """T.81 Annex C: symbol -> (code, length)."""
    codes = {}
    code, k = 0, 0
    for length in range(1, 17):
        for _ in range(bits[length - 1]):
            codes[vals[k]] = (code, length)
            code += 1
            k += 1
        code <<= 1
    return codes


# ------------------------------------------------------------------ bit writer + scans ---------


class BitWriter:
    def __init__(self):
        self.out = bytearray()
        self.acc = 0
        self.n = 0

    def put(self, value, nbits):
        if nbits == 0:
            return
        self.acc = (self.acc << nbits) | (value & ((1 << nbits) - 1))
        self.n += nbits
        while self.n >= 8:
            b = (self.acc >> (self.n - 8)) & 0xFF
            self.out.append(b)
            if b == 0xFF:
                self.out.append(0)
            self.n -= 8
        self.acc &= (1 << self.n) - 1

    def flush(self):  # pad with 1 bits to a byte boundary
        if self.n:
            self.put((1 << (8 - self.n)) - 1, 8 - self.n)


def category(v):
    return abs(v).bit_length()


def extra_bits(v, n):
    return v if v >= 0 else v + (1 << n) - 1


def scan_mcus(f, comps):
    """The MCU list of a scan over the component indexes `comps`: each MCU is a list of
    (component, bx, by)."""
    mcus = []
    if len(comps) > 1:
        for my in range(f.mcusy):
            for mx in range(f.mcusx):
                m = []
                for ci in comps:
                    c = f.comps[ci]
                    for j in range(c["v"]):
                        for i in range(c["h"]):
                            m.append((ci, mx * c["h"] + i, my * c["v"] + j))
                mcus.append(m)
    else:
        c = f.comps[comps[0]]
        for by in range(c["nby"]):
            for bx in range(c["nbx"]):
                mcus.append([(comps[0], bx, by)])
    return mcus


def sequential_events(f, scan, ri):
    """Events for a sequential scan. ('h', class, table, symbol), ('b', value, nbits), ('rst',)."""
    ev = []
    pred = {ci: 0 for ci in scan["comps"]}
    for n, mcu in enumerate(scan_mcus(f, scan["comps"])):
        if ri and n and n % ri == 0:
            ev.append(("rst",))
            pred = {ci: 0 for ci in scan["comps"]}
        for ci, bx, by in mcu:
            blk = f.coefs[ci][by][bx]
            dt, at = scan["dctab"][ci], scan["actab"][ci]
            diff = blk[0] - pred[ci]
            pred[ci] = blk[0]
            t = category(diff)
            assert t <= 11
            ev.append(("h", 0, dt, t))
            if t:
                ev.append(("b", extra_bits(diff, t), t))
            run = 0
            for k in range(1, 64):
                v = blk[ZZ[k]]
                if v == 0:
                    run += 1
                    continue
                while run > 15:
                    ev.append(("h", 1, at, 0xF0))
                    run -= 16
                s = category(v)
                assert s <= 10
                ev.append(("h", 1, at, (run << 4) | s))
                ev.append(("b", extra_bits(v, s), s))
                run = 0
            if run:
                ev.append(("h", 1, at, 0x00))
    return ev


def build_tables(ev, mode):
    """Per (class, id) Huffman tables from the events' symbol statistics."""
    used = {}
    for e in ev:
        if e[0] == "h":
            used.setdefault((e[1], e[2]), []).append(e[3])
    tables = {}
    for key, syms in used.items():
        freq = [0] * 256
        for s in syms:
            freq[s] += 1
        m = mode(key) if callable(mode) else mode
        if m == "skew":
            tables[key] = skewed_table(syms)
        elif m == "flat":
            tables[key] = flat_table(syms)
        else:
            tables[key] = optimal_table(freq)
    return tables


def write_entropy(ev, tables, ri):
    codes = {k: canonical_codes(*t) for k, t in tables.items()}
    bw = BitWriter()
    rst = 0
    for e in ev:
        if e[0] == "h":
            code, length = codes[(e[1], e[2])][e[3]]
            bw.put(code, length)
        elif e[0] == "b":
            bw.put(e[1], e[2])
        else:
            bw.flush()
            bw.out += bytes([0xFF, 0xD0 + (rst & 7)])
            rst += 1
    bw.flush()
    return bytes(bw.out)


