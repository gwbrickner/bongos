class Rng:
    """xorshift32, so fixtures never depend on a Python version's `random`."""

    def __init__(self, seed):
        self.s = seed & 0xFFFFFFFF or 0x9E3779B9

    def next(self):
        x = self.s
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        self.s = x
        return x

    def below(self, n):
        return self.next() % n

    def range(self, lo, hi):  # inclusive
        return lo + self.below(hi - lo + 1)


# ------------------------------------------------------------------ zigzag (T.81 Figure A.6) --


def make_zigzag():
    order = []
    for s in range(15):
        diag = [(y, s - y) for y in range(8) if 0 <= s - y < 8]  # (row, col)
        if s % 2 == 0:
            diag.reverse()  # even diagonals run bottom-left to top-right... see check below
        order.extend(r * 8 + c for r, c in diag)
    return order


ZZ = make_zigzag()
assert ZZ[:10] == [0, 1, 8, 16, 9, 2, 3, 10, 17, 24] and ZZ[-1] == 63 and sorted(ZZ) == list(range(64))

