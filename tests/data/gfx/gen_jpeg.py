records = []


def add_record(name, data, status, frame=None, qs=None, crc=False, wh=(0, 0)):
    w, h = (frame.w, frame.h) if frame else wh
    rec = bytearray()
    nm = name.encode()
    rec += struct.pack("<H", len(nm)) + nm
    rec += struct.pack("<iBIII", status, 1 if crc else 0, w, h, len(data)) + data
    if status == STATUS_OK:
        rows = frame.expected(qs)
        px = b"".join(struct.pack("<I", p) for row in rows for p in row)
        rec += struct.pack("<I", zlib.crc32(px) & 0xFFFFFFFF) if crc else px
    records.append(bytes(rec))


