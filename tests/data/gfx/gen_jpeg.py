def seg(marker, payload):
    return bytes([0xFF, marker]) + struct.pack(">H", len(payload) + 2) + payload


def dqt_segment(tables, use16):
    p = bytearray()
    for tid, q in sorted(tables.items()):
        if use16:
            p.append(0x10 | tid)
            for k in range(64):
                p += struct.pack(">H", q[ZZ[k]])
        else:
            p.append(tid)
            for k in range(64):
                p.append(q[ZZ[k]])
    return seg(0xDB, bytes(p))


def dht_segment(tables):
    p = bytearray()
    for (cls, tid), (bits, vals) in sorted(tables.items()):
        p.append((cls << 4) | tid)
        p += bytes(bits)
        p += bytes(vals)
    return seg(0xC4, bytes(p))


def encode(f, scans, opt=None):
    """scans: list of dicts {comps, ss, se, ah, al, dctab{ci:id}, actab{ci:id}, dqt: {id: q}?}.
    opt: sof (0/1/2), ri, jfif, adobe (None/0/1), dqt16, tabmode, fill, junk, junk_rst."""
    opt = opt or {}
    sof = opt.get("sof", 0)
    ri = opt.get("ri", 0)
    fill = opt.get("fill", False)
    out = bytearray(b"\xff\xd8")

    def add(b):
        if fill:
            out.extend(b"\xff\xff")
        out.extend(b)

    if opt.get("jfif"):
        add(seg(0xE0, b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"))
    if opt.get("adobe") is not None:
        add(seg(0xEE, b"Adobe\x00\x64\x00\x00\x00\x00" + bytes([opt["adobe"]])))
    if opt.get("comment"):
        add(seg(0xFE, b"generated by gen_jpeg.py"))
    qcur = {}
    for c in f.comps:
        qcur[c["tq"]] = f.qtables[c["tq"]]
    add(dqt_segment(qcur, opt.get("dqt16", False)))
    sofp = bytearray([8]) + struct.pack(">HH", f.h, f.w) + bytes([len(f.comps)])
    for c in f.comps:
        sofp += bytes([c["id"], (c["h"] << 4) | c["v"], c["tq"]])
    add(seg(0xC0 + sof, bytes(sofp)))
    latched = [None] * len(f.comps)
    for si, s in enumerate(scans):
        if "dqt" in s:  # a DQT redefinition between scans
            qcur.update(s["dqt"])
            add(dqt_segment(s["dqt"], opt.get("dqt16", False)))
        for ci in s["comps"]:
            if latched[ci] is None:
                latched[ci] = list(qcur[f.comps[ci]["tq"]])
        if "dri" in s:
            ri = s["dri"]
        add(seg(0xDD, struct.pack(">H", ri)))
        ev = s["events"](f, s, ri) if callable(s.get("events")) else sequential_events(f, s, ri)
        tables = build_tables(ev, s.get("tabmode", opt.get("tabmode", "opt")))
        if tables:
            add(dht_segment(tables))
        sp = bytearray([len(s["comps"])])
        for ci in s["comps"]:
            sp += bytes([f.comps[ci]["id"], (s["dctab"].get(ci, 0) << 4) | s["actab"].get(ci, 0)])
        sp += bytes([s["ss"], s["se"], (s["ah"] << 4) | s["al"]])
        add(seg(0xDA, bytes(sp)))
        data = write_entropy(ev, tables, ri)
        if opt.get("junk") or opt.get("junk_rst"):
            data = inject_junk(data, opt.get("junk_rst", False))
        out.extend(data)
    if fill:
        out.extend(b"\xff\xff")
    out.extend(b"\xff\xd9")
    return bytes(out), latched


def inject_junk(data, before_rst_only):
    """Extraneous bytes (no 0xFF) between the end of entropy data and the marker that follows."""
    out = bytearray()
    i = 0
    while i < len(data):
        if data[i] == 0xFF and data[i + 1] != 0:
            out += b"\x12\x34" + data[i:i + 2]
            i += 2
        else:
            out.append(data[i])
            i += 1
    if not before_rst_only:
        out += b"\x55"
    return bytes(out)


def seq_scans(f, script, dctab=None, actab=None):
    """script: 'inter' (one interleaved scan), 'split' (one scan per component), 'ycc' (Y, then
    Cb+Cr), 'nonint' alias of split."""
    n = len(f.comps)
    dctab = dctab or {ci: (0 if ci == 0 else 1) for ci in range(n)}
    actab = actab or dict(dctab)
    groups = {"inter": [list(range(n))], "split": [[i] for i in range(n)], "nonint": [[i] for i in range(n)],
              "ycc": [[0], [1, 2]] if n == 3 else [list(range(n))]}[script]
    return [{"comps": g, "ss": 0, "se": 63, "ah": 0, "al": 0,
             "dctab": {ci: dctab[ci] for ci in g}, "actab": {ci: actab[ci] for ci in g}} for g in groups]



# ------------------------------------------------------------------ progressive scans ----------


class EobState:
    def __init__(self):
        self.run = 0
        self.be = []  # buffered correction bits belonging to the pending EOB run


def flush_eobrun(st, ev, at):
    if st.run > 0:
        nb = st.run.bit_length() - 1
        ev.append(("h", 1, at, nb << 4))
        if nb:
            ev.append(("b", st.run & ((1 << nb) - 1), nb))
        for bit in st.be:
            ev.append(("b", bit, 1))
        st.run = 0
        st.be = []


def ac_first_block(blk, ss, se, al, at, st, ev):
    r = 0
    for k in range(ss, se + 1):
        v = blk[ZZ[k]]
        temp = ((-v) >> al) if v < 0 else (v >> al)
        if temp == 0:
            r += 1
            continue
        flush_eobrun(st, ev, at)
        while r > 15:
            ev.append(("h", 1, at, 0xF0))
            r -= 16
        nb = temp.bit_length()
        assert nb <= 10
        ev.append(("h", 1, at, (r << 4) | nb))
        ev.append(("b", temp if v >= 0 else (~temp) & ((1 << nb) - 1), nb))
        r = 0
    if r > 0:
        st.run += 1
        if st.run == 0x7FFF:
            flush_eobrun(st, ev, at)


def ac_refine_block(blk, ss, se, al, at, st, ev):
    absv = {}
    eob = 0
    for k in range(ss, se + 1):
        temp = abs(blk[ZZ[k]]) >> al
        absv[k] = temp
        if temp == 1:
            eob = k
    r = 0
    br = []
    for k in range(ss, se + 1):
        temp = absv[k]
        if temp == 0:
            r += 1
            continue
        while r > 15 and k <= eob:
            flush_eobrun(st, ev, at)
            ev.append(("h", 1, at, 0xF0))
            r -= 16
            for bit in br:
                ev.append(("b", bit, 1))
            br = []
        if temp > 1:
            br.append(temp & 1)
            continue
        flush_eobrun(st, ev, at)
        ev.append(("h", 1, at, (r << 4) | 1))
        ev.append(("b", 1 if blk[ZZ[k]] >= 0 else 0, 1))
        for bit in br:
            ev.append(("b", bit, 1))
        br = []
        r = 0
    if r > 0 or br:
        st.run += 1
        st.be.extend(br)
        if st.run == 0x7FFF:
            flush_eobrun(st, ev, at)


def progressive_events(f, scan, ri):
    ss, se, ah, al = scan["ss"], scan["se"], scan["ah"], scan["al"]
    ev = []
    if ss == 0:  # DC scan (may be interleaved)
        pred = {ci: 0 for ci in scan["comps"]}
        for n, mcu in enumerate(scan_mcus(f, scan["comps"])):
            if ri and n and n % ri == 0:
                ev.append(("rst",))
                pred = {ci: 0 for ci in scan["comps"]}
            for ci, bx, by in mcu:
                v = f.coefs[ci][by][bx][0]
                if ah == 0:
                    sv = v >> al
                    diff = sv - pred[ci]
                    pred[ci] = sv
                    t = category(diff)
                    assert t <= 11
                    ev.append(("h", 0, scan["dctab"][ci], t))
                    if t:
                        ev.append(("b", extra_bits(diff, t), t))
                else:
                    ev.append(("b", (v >> al) & 1, 1))
    else:
        assert len(scan["comps"]) == 1
        ci = scan["comps"][0]
        at = scan["actab"][ci]
        st = EobState()
        for n, mcu in enumerate(scan_mcus(f, scan["comps"])):
            if ri and n and n % ri == 0:
                flush_eobrun(st, ev, at)
                ev.append(("rst",))
            _, bx, by = mcu[0]
            blk = f.coefs[ci][by][bx]
            (ac_first_block if ah == 0 else ac_refine_block)(blk, ss, se, al, at, st, ev)
        flush_eobrun(st, ev, at)
    return ev


def prog_scans(f, script, ids=None):
    n = len(f.comps)
    ids = ids or {ci: (0 if ci == 0 else 1) for ci in range(n)}

    def sc(comps, ss, se, ah, al):
        return {"comps": comps, "ss": ss, "se": se, "ah": ah, "al": al, "events": progressive_events,
                "dctab": {ci: ids[ci] for ci in comps}, "actab": {ci: ids[ci] for ci in comps}}

    allc = list(range(n))
    blocks = sum(c["h"] * c["v"] for c in f.comps)
    dcgroups = [allc] if blocks <= 10 else [[ci] for ci in allc]
    out = []
    if script == "default":  # libjpeg's simple progression
        for g in dcgroups:
            out.append(sc(g, 0, 0, 0, 1))
        out.append(sc([0], 1, 5, 0, 2))
        for ci in reversed(allc[1:]):
            out.append(sc([ci], 1, 63, 0, 1))
        out.append(sc([0], 6, 63, 0, 2))
        out.append(sc([0], 1, 63, 2, 1))
        for g in dcgroups:
            out.append(sc(g, 0, 0, 1, 0))
        for ci in reversed(allc[1:]):
            out.append(sc([ci], 1, 63, 1, 0))
        out.append(sc([0], 1, 63, 1, 0))
    elif script == "deep":  # successive approximation 3 -> 2 -> 1 -> 0, DC per component
        for ci in allc:
            out.append(sc([ci], 0, 0, 0, 3))
        for ci in allc:
            out.append(sc([ci], 1, 63, 0, 3))
        for a in (3, 2, 1):
            for ci in allc:
                out.append(sc([ci], 0, 0, a, a - 1))
            for ci in allc:
                out.append(sc([ci], 1, 63, a, a - 1))
    elif script == "bands":  # spectral selection only, odd bands
        for g in dcgroups:
            out.append(sc(g, 0, 0, 0, 0))
        for ci in allc:
            for lo, hi in ((1, 1), (2, 9), (10, 63)):
                out.append(sc([ci], lo, hi, 0, 0))
    else:
        raise ValueError(script)
    return out


def prog_variants(f, grp, lname, scripts=("default", "deep", "bands"), extra=()):
    for sc in scripts:
        data, lat = encode(f, prog_scans(f, sc), {"sof": 2, "jfif": True})
        add_record("jg_%s__prog_%s" % (grp, sc), data, STATUS_OK, f)
    for ri in extra:
        data, lat = encode(f, prog_scans(f, "default"), {"sof": 2, "ri": ri})
        add_record("jg_%s__prog_default_ri%d" % (grp, ri), data, STATUS_OK, f)


